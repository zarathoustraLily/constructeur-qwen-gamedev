file_extensions = ['.json', '.tres', '.gd', '.tscn', '.csv', '.md']
total_replacements = 0

for root, dirs, files in os.walk('.'):
    for fn in files:
        if any(fn.endswith(ext) for ext in file_extensions):
            fp = os.path.join(root, fn)
            try:
                with open(fp, encoding='utf-8') as f:
                    content = f.read()
            except:
                continue

            original = content
            count = 0

            # Apply all rename maps
            for rename_map in [ATTACK_RENAME, ENTITY_RENAME, EFFECT_RENAME, UI_RENAME, OTHER_RENAME]:
                for old, new in rename_map.items():
                    if old in content:
                        content = content.replace(old, new)
                        count += content.count(new) - original.count(new)

            if content != original:
                with open(fp, 'w', encoding='utf-8') as f:
                    f.write(content)
                total_replacements += 1
                print(f'Updated: {fp} ({count} replacements)')

print(f'\nTotal files updated: {total_replacements}')
